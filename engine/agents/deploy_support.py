def prepare_publish_files(staged_dir: Path, request: DeployRequest, include_ci: bool = False) -> list[str]:
    """Add only missing publish metadata to the staged copy."""
    staged = Path(staged_dir)
    if not staged.is_dir() or staged.is_symlink():
        raise ValueError("staged_dir must be an existing directory")
    added: list[str] = []

    def add(relative: str, contents: str) -> None:
        path = staged / relative
        if path.exists() or path.is_symlink():
            return
        parent = path.parent
        while parent != staged:
            if parent.is_symlink():
                raise ValueError("staged publish path must not traverse a symlink")
            parent = parent.parent
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(redact(contents))
        added.append(relative)

    readme = [
        f"# {redact(request.repo_name)}",
        "",
        "Generated by AgentForge.",
        "",
        f"Run ID: {redact(request.run_id)}",
        f"Checkpoint ID: {redact(request.checkpoint_id or '')}",
    ]
    if (staged / "backend").is_dir():
        readme.extend(["", "## Backend", "", "python -m uvicorn backend.app:app --reload"])
    if (staged / "frontend" / "package.json").is_file():
        readme.extend(["", "## Frontend", "", "npm install", "npm run dev"])
    add("README.md", "\n".join(readme) + "\n")

    year = datetime.now(timezone.utc).year
    license_text = (
        f"MIT License\n\nCopyright (c) {year} AgentForge contributors\n\n"
        "Permission is hereby granted, free of charge, to any person obtaining a copy\n"
        "of this software and associated documentation files (the \"Software\"), to deal\n"
        "in the Software without restriction, including without limitation the rights\n"
        "to use, copy, modify, merge, publish, distribute, sublicense, and/or sell\n"
        "copies of the Software, and to permit persons to whom the Software is\n"
        "furnished to do so, subject to the following conditions:\n\n"
        "The above copyright notice and this permission notice shall be included in all\n"
        "copies or substantial portions of the Software.\n\n"
        "THE SOFTWARE IS PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR\n"
        "IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,\n"
        "FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE\n"
        "AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER\n"
        "LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,\n"
        "OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE\n"
        "SOFTWARE.\n"
    )
    add("LICENSE", license_text)
    add(".gitignore", _GITIGNORE)

    if include_ci:
        steps = [
            "# Pushing workflow files needs Workflows (fine-grained) or workflow (classic) token permission.",
            "name: CI",
            "on: [push]",
            "jobs:",
            "  build:",
            "    runs-on: ubuntu-latest",
            "    steps:",
            "      - uses: actions/checkout@v4",
        ]
        if (staged / "backend" / "requirements.txt").is_file():
            steps.extend(
                [
                    "      - uses: actions/setup-python@v5",
                    "        with:",
                    "          python-version: '3.12'",
                    "      - run: pip install -r backend/requirements.txt",
                    "      - run: pytest",
                ]
            )
        if (staged / "frontend" / "package.json").is_file():
            steps.extend(
                [
                    "      - uses: actions/setup-node@v4",
                    "        with:",
                    "          node-version: '20'",
                    "      - run: npm install",
                    "        working-directory: frontend",
                    "      - run: npm run build",
                    "        working-directory: frontend",
                ]
            )
        add(".github/workflows/ci.yml", "\n".join(steps) + "\n")
    return added


class HealthResult:
    def __init__(self, passed: bool, status_code: int | None, attempts: int, error: str | None = None) -> None:
        self.passed = passed
        self.status_code = status_code
        self.attempts = attempts
        self.error = redact(error) if error else None


class HealthChecker(Protocol):
    def check(
        self, base_url: str, path: str, retries: int = 5, delay: float = 1.0, timeout: float = 10.0
    ) -> HealthResult: ...


class HttpxHealthChecker:
    def __init__(
        self, transport: httpx.BaseTransport | None = None, sleep: Callable[[float], None] = time.sleep
    ) -> None:
        self._transport = transport
        self._sleep = sleep

    def check(
        self, base_url: str, path: str, retries: int = 5, delay: float = 1.0, timeout: float = 10.0
    ) -> HealthResult:
        parsed = urlsplit(base_url)
        if parsed.scheme not in {"http", "https"} or not parsed.netloc:
            return HealthResult(False, None, 0, "health URL must use http or https")
        if not path.startswith("/") or ".." in path or any(char.isspace() for char in path):
            return HealthResult(False, None, 0, "invalid health check path")
        attempts = max(1, min(int(retries), 10))
        status_code: int | None = None
        error: str | None = None
        for attempt in range(1, attempts + 1):
            try:
                with httpx.Client(transport=self._transport, timeout=timeout, follow_redirects=False) as client:
                    response = client.get(base_url.rstrip("/") + path)
                status_code = response.status_code
                if 200 <= status_code < 300:
                    return HealthResult(True, status_code, attempt)
                error = f"health check returned HTTP {status_code}"
            except (httpx.TimeoutException, httpx.TransportError) as exc:
                error = f"health check request failed: {redact(exc)}"
            if attempt < attempts:
                self._sleep(delay)
        return HealthResult(False, status_code, attempts, error)


class FakeHealthChecker:
    def __init__(self, results: list[HealthResult] | None = None) -> None:
        self.results = list(results or [])
        self.calls: list[tuple[str, str, int, float, float]] = []

    def check(
        self, base_url: str, path: str, retries: int = 5, delay: float = 1.0, timeout: float = 10.0
    ) -> HealthResult:
        self.calls.append((redact(base_url), redact(path), retries, delay, timeout))
        if not self.results:
            return HealthResult(False, None, 0, "no scripted health result")
        return self.results.pop(0)


class DeployTarget(Protocol):
    name: str

    def is_configured(self) -> bool: ...

    def deploy(self, staged_dir: Path, request: DeployRequest, repo: RepoInfo) -> DeploymentStatus: ...

    def rollback(self, previous: DeploymentStatus) -> DeploymentStatus: ...


class DisabledTarget:
    name = "disabled"

    def is_configured(self) -> bool:
        return False

    def deploy(self, staged_dir: Path, request: DeployRequest, repo: RepoInfo) -> DeploymentStatus:
        return DeploymentStatus(id="disabled", status="failed", target=self.name, error="deployment not configured")

    def rollback(self, previous: DeploymentStatus) -> DeploymentStatus:
        return DeploymentStatus(id="disabled", status="failed", target=self.name, error="deployment not configured")


class NebiusServerlessTarget:
    """Nebius Serverless AI endpoints (docs.nebius.com/serverless/endpoints/manage, checked 2026-10-30): an endpoint
    runs a container IMAGE, is created with `nebius ai endpoint create --name --image --container-port ...` or
    POST https://api.nebius.cloud/ai/v1/endpoints with a Nebius AI Cloud IAM token and project id (the Token Factory
    API key is not valid there), takes ~5 minutes and bills a VM. Its HTTPS URL is status.public_endpoints[].
    The adapter (image build + registry push + endpoint create/delete) is NOT implemented, so this target is never
    configured; missing_requirements() says what an implementation would need."""

    name = "nebius_serverless"

    def missing_requirements(self, env: dict[str, str] | None = None) -> list[str]:
        import os
        import shutil

        env = dict(os.environ) if env is None else env
        missing = ["adapter not implemented (container image build + push + `nebius ai endpoint create`)"]
        if not shutil.which("nebius"):
            missing.append("Nebius AI Cloud CLI (`nebius`) not installed")
        if not env.get("NEBIUS_PROJECT_ID"):
            missing.append("NEBIUS_PROJECT_ID (Nebius AI Cloud project) not set")
        if not env.get("NEBIUS_IAM_TOKEN") and not (Path.home() / ".nebius" / "config.yaml").is_file():
            missing.append("Nebius AI Cloud IAM credentials (CLI profile or NEBIUS_IAM_TOKEN) not configured")
        if not env.get("NEBIUS_CONTAINER_REGISTRY"):
            missing.append("NEBIUS_CONTAINER_REGISTRY for the app image not set")
        return missing

    def is_configured(self) -> bool:
        return False

    def deploy(self, staged_dir: Path, request: DeployRequest, repo: RepoInfo) -> DeploymentStatus:
        # TODO: Add a documented Nebius Serverless API adapter after its contract is available.
        raise NotConfigured("Nebius Serverless deployment is not implemented yet")

    def rollback(self, previous: DeploymentStatus) -> DeploymentStatus:
        # TODO: Add a documented Nebius Serverless rollback adapter after its contract is available.
        raise NotConfigured("Nebius Serverless deployment is not implemented yet")


class FakeDeployTarget:
    name = "fake"

    def __init__(
        self,
        outcomes: list[DeploymentStatus] | None = None,
        rollback_outcomes: list[DeploymentStatus] | None = None,
    ) -> None:
        self.outcomes = list(outcomes or [])
        self.rollback_outcomes = list(rollback_outcomes or [])
        self.deploy_calls: list[tuple[Path, DeployRequest, RepoInfo]] = []
        self.rollback_calls: list[DeploymentStatus] = []

    def is_configured(self) -> bool:
        return True

    def deploy(self, staged_dir: Path, request: DeployRequest, repo: RepoInfo) -> DeploymentStatus:
        self.deploy_calls.append((Path(staged_dir), request, repo))
        if self.outcomes:
            return self.outcomes.pop(0)
        return DeploymentStatus(id="fake-empty", status="failed", target=self.name, error="no scripted outcome")

    def rollback(self, previous: DeploymentStatus) -> DeploymentStatus:
        self.rollback_calls.append(previous)
        if self.rollback_outcomes:
            return self.rollback_outcomes.pop(0)
        return DeploymentStatus(id="fake-empty-rollback", status="failed", target=self.name, error="no scripted rollback outcome")


class DeploymentHistory:
    def __init__(self, path: Path) -> None:
        self.path = Path(path)

    def _entries(self) -> list[dict]:
        try:
            contents = json.loads(self.path.read_text(encoding="utf-8"))
            return contents if isinstance(contents, list) else []
        except (OSError, ValueError):
            return []

    def add(self, run_id: str, checkpoint_id: str, status: DeploymentStatus) -> None:
        entries = self._entries()
        entries.append(
            redact(
                {
                    "run_id": run_id,
                    "checkpoint_id": checkpoint_id,
                    "deployment": status.model_dump(mode="json"),
                }
            )
        )
        self.path.parent.mkdir(parents=True, exist_ok=True)
        temporary: Path | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", dir=self.path.parent, prefix=".deployments-", suffix=".tmp", delete=False
            ) as handle:
                temporary = Path(handle.name)
                json.dump(redact(entries), handle, indent=2)
                handle.write("\n")
            temporary.replace(self.path)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)

    def _find(self, run_id: str, checkpoint_id: str | None = None, exclude_id: str | None = None) -> DeploymentStatus | None:
        for entry in reversed(self._entries()):
            try:
                if entry["run_id"] != run_id or (checkpoint_id is not None and entry["checkpoint_id"] != checkpoint_id):
                    continue
                status = DeploymentStatus.model_validate(redact(entry["deployment"]))
                if status.id == exclude_id:
                    continue
                if checkpoint_id is None and status.status != "healthy":
                    continue
                return status
            except (KeyError, TypeError, ValueError):
                continue
        return None

    def latest_healthy(self, run_id: str, exclude_id: str | None = None) -> DeploymentStatus | None:
        return self._find(run_id, exclude_id=exclude_id)

    def for_checkpoint(self, run_id: str, checkpoint_id: str) -> DeploymentStatus | None:
        return self._find(run_id, checkpoint_id=checkpoint_id)


class CheckpointVerifier(Protocol):
    def is_approved(self, run_id: str, checkpoint_id: str, git_tag: str) -> bool: ...


class FileCheckpointVerifier:
    _ID = re.compile(r"^[A-Za-z0-9._-]{1,128}$")

    def __init__(self, workspace_root: Path) -> None:
        self.workspace_root = Path(workspace_root)

    def is_approved(self, run_id: str, checkpoint_id: str, git_tag: str) -> bool:
        if not isinstance(checkpoint_id, str) or not self._ID.fullmatch(checkpoint_id) or ".." in checkpoint_id:
            return False
        file = self.workspace_root / ".agentforge" / "checkpoints" / f"{checkpoint_id}.json"
        if file.is_symlink():
            return False
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
            return (
                isinstance(data, dict)
                and data.get("id") == checkpoint_id
                and data.get("git_tag") == git_tag
                and data.get("run_id", run_id) == run_id
            )
        except (OSError, ValueError, TypeError):
            return False
