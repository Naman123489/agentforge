"""Model-assisted failure analysis for the Reviewer (root cause, owner, file, concrete fix).

Runs only AFTER the deterministic verdict rejected a stage, and only explains it: the verdict is never passed to or
changed by this module. Context is focused: failing checks' log tails, source lines around the locations the logs
name, and the contract operations the logs mention. Output is schema-validated; files the model names must exist in
the workspace, otherwise they are dropped. Any failure falls back to the deterministic explanations.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from .explanations import fallback_explanations
from .schemas import InternalCheckResult, RequiredFix

Category = Literal["syntax", "type_error", "test_failure", "contract_mismatch", "runtime_error", "build_config",
                   "missing_file", "security", "other"]


class Finding(BaseModel):
    check: str
    owner: Literal["backend", "frontend", "planner", "shared"]
    file: str | None = None
    category: Category
    root_cause: str = Field(max_length=600)
    suggestion: str = Field(max_length=800)


class Analysis(BaseModel):
    findings: list[Finding] = Field(max_length=8)


SYSTEM = """\
[agent:reviewer] You are the Reviewer/Integrator of AgentForge. Executed checks have ALREADY rejected this stage;
you do not decide approval. For each failing check, find the root cause in the evidence and the smallest fix.
Reply with ONE JSON object only:
{"findings": [{"check": "<failing check name>", "owner": "backend|frontend|planner|shared",
  "file": "<workspace-relative path or null>", "category": "syntax|type_error|test_failure|contract_mismatch|
  runtime_error|build_config|missing_file|security|other", "root_cause": "<what is wrong and why, 1-2 sentences>",
  "suggestion": "<the concrete change: which function/line, what to write instead>"}]}
Workspace: contract/openapi.yaml and types.ts are generated by the Planner (owner "planner"); backend/ (FastAPI +
SQLite) is the Backend agent's; frontend/ (React + TypeScript + Vite) is the Frontend agent's.
Rules: cite only files that appear in the evidence, with workspace-relative paths. If several checks fail for one cause, report it once and name
the first failing check. If the evidence is insufficient, say so in root_cause; do not guess file names.
"""

# Locations the engine's checks print: python tracebacks, pytest, ruff, tsc, vite.
_LOC = [
    re.compile(r'File "(?:[^"]*?[\\/])?((?:backend|frontend)[\\/][^"]+)", line (\d+)'),
    re.compile(r"\b((?:backend|frontend)/[\w./-]+\.(?:py|tsx?|jsx?|json|ya?ml|css|html)):(\d+)"),
    re.compile(r"\b((?:frontend/)?src/[\w./-]+\.tsx?)\((\d+),\d+\)"),
]
_PATH_IN_LOG = re.compile(r"\b(?:GET|POST|PUT|PATCH|DELETE)?\s*(/api/[\w/{}.-]*)")


def _locations(text: str) -> list[tuple[str, int]]:
    out: list[tuple[str, int]] = []
    for rx in _LOC:
        for m in rx.finditer(text):
            path = m.group(1).replace("\\", "/")
            if path.startswith("src/"):
                path = "frontend/" + path
            if (path, int(m.group(2))) not in out:
                out.append((path, int(m.group(2))))
    return out


def build_context(root: Path, failing: list[InternalCheckResult], contract_yaml: str = "",
                  previous_fixes: list[str] | None = None, log_chars: int = 1800, max_snippets: int = 6) -> str:
    parts: list[str] = []
    seen_logs: set[str] = set()
    for c in failing:
        tail = c.log_tail.strip()[-log_chars:]
        if tail in seen_logs:  # identical evidence (e.g. build and served-with-backend failing on the same error)
            parts.append(f"### {c.name}: FAILED (same log as above)")
            continue
        seen_logs.add(tail)
        parts.append(f"### {c.name}: FAILED (exit {c.exit_code})\n{tail}")
    logs = "\n".join(c.log_tail for c in failing)
    snippets = []
    for rel, line in _locations(logs)[:max_snippets]:
        p = (root / rel).resolve()
        if not p.is_file() or root.resolve() not in p.parents:
            continue
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
        lo, hi = max(0, line - 8), min(len(lines), line + 7)
        body = "\n".join(f"{'>' if i + 1 == line else ' '}{i + 1:4} {lines[i]}" for i in range(lo, hi))
        snippets.append(f"### {rel} (around line {line})\n{body}")
    if snippets:
        parts.append("## Source at the reported locations\n" + "\n".join(snippets))
    mentioned = sorted(set(_PATH_IN_LOG.findall(logs)))
    handlers = _route_handlers(root, mentioned)
    if handlers:
        parts.append("## Backend handlers for the API paths in the logs\n" + "\n".join(handlers))
    if contract_yaml and mentioned:
        keep = [ln for ln in contract_yaml.splitlines() if any(m.split("{")[0].rstrip("/") in ln for m in mentioned)]
        if keep:
            parts.append("## Contract lines for the paths in the logs\n" + "\n".join(keep[:40]))
    if previous_fixes:
        parts.append("## Fixes already suggested in the previous attempt (they did not work)\n- " + "\n- ".join(previous_fixes[:6]))
    return "\n\n".join(parts)


_ROUTE = re.compile(r"""@\w+\.(get|post|put|patch|delete)\(\s*["'](/api/[^"']*)["']""")


def _route_handlers(root: Path, paths: list[str], max_handlers: int = 4, lines_after: int = 18) -> list[str]:
    """Contract-aware context: the backend source of the routes the failing logs mention (logs show the test,
    not the handler, so without this the model cannot see the code it should fix)."""
    out: list[str] = []
    wanted = {p.rstrip("/") for p in paths}
    for py in sorted((root / "backend").rglob("*.py")) if (root / "backend").is_dir() else []:
        if py.name.startswith("test_") or "tests" in py.parts:
            continue
        lines = py.read_text(encoding="utf-8", errors="replace").splitlines()
        for i, line in enumerate(lines):
            m = _ROUTE.search(line)
            if m and (m.group(2).rstrip("/") in wanted or re.sub(r"\{[^}]+\}", "", m.group(2)).rstrip("/") in wanted):
                rel = py.relative_to(root).as_posix()
                body = "\n".join(f"{j + 1:4} {lines[j]}" for j in range(i, min(len(lines), i + lines_after)))
                out.append(f"### {rel} line {i + 1}: {m.group(1).upper()} {m.group(2)}\n{body}")
                if len(out) >= max_handlers:
                    return out
    return out


def _normalize(root: Path, file: str) -> str | None:
    file = file.replace("\\", "/").removeprefix("./")
    for candidate in (file, f"frontend/{file}", f"backend/{file}"):  # tsc/vite print paths relative to frontend/
        if ".." not in candidate.split("/") and (root / candidate).is_file():
            return candidate
    return None


def _clean(root: Path, findings: list[Finding], failing_names: set[str]) -> list[RequiredFix]:
    fixes = []
    for f in findings:
        file = _normalize(root, f.file) if f.file else None
        if file and (".." in file.split("/") or not (root / file).is_file()):
            file = None  # hallucinated or unsafe path: keep the advice, drop the location
        fixes.append(RequiredFix(owner=f.owner, file=file, category=f.category,
                                 problem=f"{f.check if f.check in failing_names else 'review'}: {f.root_cause}",
                                 suggestion=f.suggestion))
    return fixes


async def analyze_failures(router, root: Path, failing: list[InternalCheckResult], stage_id: str,
                           contract_yaml: str = "", previous_fixes: list[str] | None = None,
                           task_type: str = "complex_debug") -> tuple[list[RequiredFix], dict]:
    """Returns (fixes, meta). meta says whether the model was used, which one, tokens, cost and latency."""
    meta: dict = {"source": "deterministic"}
    if not failing:
        return [], meta
    if router is None:
        return fallback_explanations(failing), meta
    ctx = build_context(root, failing, contract_yaml, previous_fixes)
    try:
        res = await router.call("reviewer", [{"role": "system", "content": SYSTEM}, {"role": "user", "content": ctx}],
                                Analysis, task_type=task_type, stage_id=stage_id, max_tokens=16000)  # reasoning models think first: 3000 left no room for the JSON
        fixes = _clean(root, res.parsed.findings, {c.name for c in failing})
        if not fixes:
            raise ValueError("model returned no findings")
        meta = {"source": "model", "model_id": res.model_id, "input_tokens": res.input_tokens,
                "output_tokens": res.output_tokens, "cost_usd": res.cost_usd, "latency_s": round(res.latency_s, 2),
                "context_chars": len(ctx)}
        return fixes, meta
    except Exception as e:  # noqa: BLE001 - router stop, invalid output, network: explanations are best-effort
        return fallback_explanations(failing), {"source": "deterministic", "model_error": f"{type(e).__name__}: {e}"[:300]}
