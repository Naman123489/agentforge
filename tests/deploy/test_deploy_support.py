def test_disabled_target_returns_controlled_failure(tmp_path: Path) -> None:
    target = DisabledTarget()
    repo = RepoInfo(html_url="https://example.com", clone_url="https://example.com/repo.git")
    assert not target.is_configured()
    assert target.deploy(tmp_path, request(), repo).error == "deployment not configured"
    assert target.rollback(status("old")).status == "failed"


