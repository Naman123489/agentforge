def test_fake_deploy_target_records_calls(tmp_path: Path) -> None:
    expected = status("new")
    rollback = status("old", "rolled_back")
    fake = FakeDeployTarget([expected], [rollback])
    repo = RepoInfo(html_url="https://example.com", clone_url="https://example.com/repo.git")
    assert fake.deploy(tmp_path, request(), repo) == expected
    assert fake.rollback(status("old")) == rollback
    assert len(fake.deploy_calls) == len(fake.rollback_calls) == 1


def test_history_add_latest_healthy_and_checkpoint(tmp_path: Path) -> None:
    history = DeploymentHistory(tmp_path / ".agentforge" / "deploy" / "deployments.json")
    history.add("run_1", "cp_1", status("one"))
    history.add("run_1", "cp_2", status("two", "failed"))
    history.add("run_1", "cp_3", status("three"))
    assert history.latest_healthy("run_1").id == "three"
    assert history.for_checkpoint("run_1", "cp_2").id == "two"
    assert history.latest_healthy("other") is None


