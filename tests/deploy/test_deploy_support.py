def test_history_write_is_atomic_and_redacted(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    token = "ghp_" + "x" * 36
    monkeypatch.setenv("GITHUB_TOKEN", token)
    path = tmp_path / "deployments.json"
