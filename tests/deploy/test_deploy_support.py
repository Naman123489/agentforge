def test_checkpoint_verifier_wrong_tag_and_wrong_id_fail(checkpoint_root: Path) -> None:
    verifier = FileCheckpointVerifier(checkpoint_root)
    assert not verifier.is_approved("run_1", "cp_1", "tag-2")
    assert not verifier.is_approved("run_1", "other", "tag-1")
    (checkpoint_root / ".agentforge" / "checkpoints" / "cp_1.json").write_text(json.dumps({"id": "wrong", "git_tag": "tag-1"}))
    assert not verifier.is_approved("run_1", "cp_1", "tag-1")


def test_checkpoint_verifier_missing_invalid_json_and_traversal_fail(checkpoint_root: Path) -> None:
    verifier = FileCheckpointVerifier(checkpoint_root)
    assert not verifier.is_approved("run_1", "missing", "tag-1")
    file = checkpoint_root / ".agentforge" / "checkpoints" / "cp_1.json"
    file.write_text("invalid json")
    assert not verifier.is_approved("run_1", "cp_1", "tag-1")
    assert not verifier.is_approved("run_1", "../x", "tag-1")
