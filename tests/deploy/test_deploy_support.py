def request() -> DeployRequest:
    return DeployRequest(run_id="run_1", stage_id="deploy", checkpoint_id="cp_1", git_tag="tag-1", repo_name="example")


def status(identifier: str, state: str = "healthy") -> DeploymentStatus:
    return DeploymentStatus(id=identifier, status=state, target="fake", url=f"https://example.test/{identifier}")


def test_publish_files_added_when_missing(tmp_path: Path) -> None:
    added = prepare_publish_files(tmp_path, request())
    assert added == ["README.md", "LICENSE", ".gitignore"]
    assert "Generated by AgentForge" in (tmp_path / "README.md").read_text()
    license_text = (tmp_path / "LICENSE").read_text()
    assert "MIT License" in license_text and "AgentForge contributors" in license_text
    gitignore = (tmp_path / ".gitignore").read_text()
    for entry in (".env*", "*.db", "*.sqlite", "node_modules", "__pycache__", ".venv", "dist", ".pytest_cache", ".agentforge"):
        assert entry in gitignore


def test_publish_files_do_not_overwrite_existing(tmp_path: Path) -> None:
    for name in ("README.md", "LICENSE", ".gitignore"):
        (tmp_path / name).write_text("original")
    assert prepare_publish_files(tmp_path, request()) == []
    assert all((tmp_path / name).read_text() == "original" for name in ("README.md", "LICENSE", ".gitignore"))


def test_ci_absent_by_default_and_present_when_requested(tmp_path: Path) -> None:
    prepare_publish_files(tmp_path, request())
    workflow = tmp_path / ".github" / "workflows" / "ci.yml"
    assert not workflow.exists()
    added = prepare_publish_files(tmp_path, request(), include_ci=True)
    assert added == [".github/workflows/ci.yml"]
    assert "on: [push]" in workflow.read_text()
    assert "Workflows (fine-grained)" in workflow.read_text()
    assert prepare_publish_files(tmp_path, request(), include_ci=True) == []


@pytest.mark.parametrize("backend,frontend", [(False, False), (True, False), (False, True), (True, True)])
def test_readme_run_instructions_only_for_existing_folders(tmp_path: Path, backend: bool, frontend: bool) -> None:
    if backend:
        (tmp_path / "backend").mkdir()
        (tmp_path / "backend" / "requirements.txt").write_text("fastapi")
    if frontend:
        (tmp_path / "frontend").mkdir()
        (tmp_path / "frontend" / "package.json").write_text("{}")
    prepare_publish_files(tmp_path, request(), include_ci=True)
    readme = (tmp_path / "README.md").read_text()
    workflow = (tmp_path / ".github" / "workflows" / "ci.yml").read_text()
    assert ("python -m uvicorn backend.app:app --reload" in readme) is backend
    assert ("npm install" in readme and "npm run dev" in readme) is frontend
    assert ("pip install -r backend/requirements.txt" in workflow and "- run: pytest" in workflow) is backend
    assert ("npm run build" in workflow) is frontend


def test_readme_has_no_absolute_paths_or_secrets(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("GITHUB_TOKEN", "ghp_" + "x" * 36)
    req = request().model_copy(update={"repo_name": "ghp_" + "x" * 36})
    prepare_publish_files(tmp_path, req)
    readme = (tmp_path / "README.md").read_text()
    assert "ghp_" not in readme and str(tmp_path) not in readme
    assert "C:\\" not in readme and "/home/" not in readme


def test_publish_files_reject_symlink_parent(tmp_path: Path) -> None:
    staged = tmp_path / "staging"
    staged.mkdir()
    outside = tmp_path / "outside"
    outside.mkdir()
    try:
        (staged / ".github").symlink_to(outside, target_is_directory=True)
    except (OSError, NotImplementedError):
        pytest.skip("symlinks unavailable on this system")
    with pytest.raises(ValueError, match="symlink"):
        prepare_publish_files(staged, request(), include_ci=True)
    assert list(outside.iterdir()) == []


def test_health_200_passes_first_try() -> None:
    calls = []

    def handler(req: httpx.Request) -> httpx.Response:
        calls.append(req)
        return httpx.Response(200)

    result = HttpxHealthChecker(httpx.MockTransport(handler)).check("https://app.example", "/health")
    assert result.passed and result.status_code == 200 and result.attempts == 1 and len(calls) == 1


def test_health_500_fails_after_exact_retries() -> None:
    calls, delays = [], []

    def handler(req: httpx.Request) -> httpx.Response:
        calls.append(req)
        return httpx.Response(500)

    result = HttpxHealthChecker(httpx.MockTransport(handler), sleep=delays.append).check(
        "https://app.example", "/health", retries=3, delay=0.25
    )
    assert not result.passed and result.status_code == 500 and result.attempts == len(calls) == 3
    assert delays == [0.25, 0.25]


